static bool bit_set(const uint8_t *row, int16_t sx) {
  return (row[sx >> 3] & static_cast<uint8_t>(0x80 >> (sx & 7))) != 0;
}

static void blit(int16_t x, int16_t y, uint16_t w, uint16_t h, const uint8_t *bits,
                 float scale_x, float scale_y, bool cover) {
  const int16_t dw = static_cast<int16_t>(w * scale_x + 0.5f);
  const int16_t dh = static_cast<int16_t>(h * scale_y + 0.5f);
  if (dw <= 0 || dh <= 0 || x >= kOledW || y >= kOledH || x + dw <= 0 || y + dh <= 0) {
    return;
  }
  const uint16_t stride = static_cast<uint16_t>((w + 7) / 8);
  for (int16_t py = 0; py < dh; py++) {
    const int16_t dy = static_cast<int16_t>(y + py);
    if (dy < 0 || dy >= kOledH) {
      continue;
    }
    const int16_t sy0 = static_cast<int16_t>((py * h) / dh);
    int16_t sy1 = cover ? static_cast<int16_t>(((py + 1) * h) / dh)
                        : static_cast<int16_t>(sy0 + 1);
    if (sy1 <= sy0) {
      sy1 = static_cast<int16_t>(sy0 + 1);
    }
    if (sy1 > static_cast<int16_t>(h)) {
      sy1 = static_cast<int16_t>(h);
    }
    for (int16_t px = 0; px < dw; px++) {
      const int16_t dx = static_cast<int16_t>(x + px);
      if (dx < 0 || dx >= kOledW) {
        continue;
      }
      const int16_t sx0 = static_cast<int16_t>((px * w) / dw);
      int16_t sx1 = cover ? static_cast<int16_t>(((px + 1) * w) / dw)
                          : static_cast<int16_t>(sx0 + 1);
      if (sx1 <= sx0) {
        sx1 = static_cast<int16_t>(sx0 + 1);
      }
      if (sx1 > static_cast<int16_t>(w)) {
        sx1 = static_cast<int16_t>(w);
      }
      bool ink = false;
      for (int16_t sy = sy0; sy < sy1 && !ink; sy++) {
        const uint8_t *row = bits + static_cast<size_t>(sy) * stride;
        for (int16_t sx = sx0; sx < sx1; sx++) {
          if (bit_set(row, sx)) {
            ink = true;
            break;
          }
        }
      }
      if (ink) {
        oled.drawPixel(static_cast<u8g2_uint_t>(dx), static_cast<u8g2_uint_t>(dy));
      }
    }
  }
}

