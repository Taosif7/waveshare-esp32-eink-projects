#!/usr/bin/env python3
"""Convert assets/frames/f01.png..f16.png into include/frames.h.

Each PNG is a 128x64 1-bit picture. White pixels become set bits in a PROGMEM
XBM array (LSB is the left pixel), which U8g2 drawXBM lights on the OLED.
"""

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FRAMES = ROOT / "assets" / "frames"
HEADER = ROOT / "include" / "frames.h"
WIDTH = 128
HEIGHT = 64
COUNT = 16
STRIDE = WIDTH // 8


def png_to_xbm(path):
    image = Image.open(path).convert("L")
    if image.size != (WIDTH, HEIGHT):
        raise SystemExit(f"{path.name} is {image.size[0]}x{image.size[1]}, expected {WIDTH}x{HEIGHT}")
    pixels = image.load()
    data = bytearray(STRIDE * HEIGHT)
    lit = 0
    for y in range(HEIGHT):
        for x in range(WIDTH):
            if pixels[x, y] >= 128:
                data[y * STRIDE + (x // 8)] |= 1 << (x % 8)
                lit += 1
    return bytes(data), lit


def format_array(name, blob):
    lines = [f"static const uint8_t {name}[] PROGMEM = {{"]
    for y in range(HEIGHT):
        row = blob[y * STRIDE : (y + 1) * STRIDE]
        body = ", ".join(f"0x{b:02X}" for b in row)
        lines.append(f"    {body},")
    lines.append("};")
    return "\n".join(lines)


def build():
    parts = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
        "",
        "// 128x64 XBM frames. LSB is the left pixel. White PNG pixels are lit.",
        "// Regenerated by tools/png_to_frames.py from assets/frames/f01.png..f16.png.",
        "",
        f"constexpr int kFrameWidth = {WIDTH};",
        f"constexpr int kFrameHeight = {HEIGHT};",
        f"constexpr int kFrameCount = {COUNT};",
        f"constexpr int kFrameStride = {STRIDE};",
        "constexpr int kFrameBytes = kFrameStride * kFrameHeight;",
        "",
    ]
    names = []
    for index in range(1, COUNT + 1):
        path = FRAMES / f"f{index:02d}.png"
        if not path.is_file():
            raise SystemExit(f"missing {path}")
        blob, lit = png_to_xbm(path)
        name = f"kFrame{index:02d}"
        names.append(name)
        parts.append(format_array(name, blob))
        parts.append("")
        print(f"{path.name}: {lit} lit pixels")
    parts.append("static const uint8_t *const kFrameTable[kFrameCount] = {")
    for name in names:
        parts.append(f"    {name},")
    parts.append("};")
    parts.append("")
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(parts))
    print(f"wrote {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    try:
        build()
    except SystemExit as exc:
        print(exc, file=sys.stderr)
        sys.exit(1)
