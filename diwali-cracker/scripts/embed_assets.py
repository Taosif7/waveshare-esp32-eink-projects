"""Pack data/ into src/web_assets.h so a single firmware flash serves the UI."""

Import("env")  # type: ignore[name-defined]  # noqa: F821 — PlatformIO SCons

from pathlib import Path

PROJECT = Path(env["PROJECT_DIR"]).resolve()  # type: ignore[name-defined]
DATA = PROJECT / "data"
OUT = PROJECT / "src" / "web_assets.h"
DELIM = "diwali"
BINARY_SUFFIXES = {".mp3", ".wav", ".ogg", ".bin"}


def c_string_name(rel: str) -> str:
    stem = rel.replace(".", "_").replace("-", "_").replace("/", "_")
    return f"ASSET_{stem.upper()}"


def emit_text(name: str, text: str) -> list[str]:
    if f"){DELIM}\"" in text or f"){DELIM}" in text:
        print(f"ERROR: asset contains raw-string delimiter ){DELIM}")
        env.Exit(1)  # type: ignore[name-defined]
    return [f"static const char {name}[] = R\"{DELIM}({text}){DELIM}\";", ""]


def emit_binary(name: str, data: bytes) -> list[str]:
    lines = [
        f"static const size_t {name}_LEN = {len(data)};",
        f"static const uint8_t {name}[] = {{",
    ]
    chunk = []
    for i, b in enumerate(data):
        chunk.append(f"0x{b:02x}")
        if len(chunk) == 16:
            lines.append("  " + ", ".join(chunk) + ",")
            chunk = []
    if chunk:
        lines.append("  " + ", ".join(chunk) + ",")
    lines.append("};")
    lines.append("")
    return lines


parts = [
    "// Auto-generated by scripts/embed_assets.py — do not edit.",
    "#pragma once",
    "",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
]

files = sorted(p for p in DATA.rglob("*") if p.is_file())
if not files:
    print(f"ERROR: no assets in {DATA}")
    env.Exit(1)  # type: ignore[name-defined]

for path in files:
    rel = path.relative_to(DATA).as_posix()
    name = c_string_name(rel)
    if path.suffix.lower() in BINARY_SUFFIXES:
        parts.extend(emit_binary(name, path.read_bytes()))
        print(f"  bin  {rel} ({path.stat().st_size} bytes)")
    else:
        parts.extend(emit_text(name, path.read_text(encoding="utf-8")))
        print(f"  text {rel}")

OUT.write_text("\n".join(parts), encoding="utf-8")
print(f"Embedded {len(files)} asset(s) → {OUT.relative_to(PROJECT)} ({OUT.stat().st_size} bytes)")
